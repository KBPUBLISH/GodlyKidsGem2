#!/usr/bin/env node
/**
 * Generates homeworld/CHARACTERS.md from homeworld/src/characters.mjs (node, no dependencies).
 * Run from homeworld/: `npm run characters:md`. Edit characters.mjs, never the markdown.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {CHARACTERS,BIBLE_CHARACTERS,ROLES,CONSUMERS,promptSummary} from '../src/characters.mjs';

const here=path.dirname(fileURLToPath(import.meta.url));
const out=path.resolve(here,'..','CHARACTERS.md');
const cell=v=>String(v).replace(/\|/g,'\\|');
const list=v=>v.length?v.join(', '):'—';
const tasks=c=>c.tasks.map(t=>t.silly?`${t.text} *(silly)*`:t.text).join(', ');

const lines=[];
const p=(...xs)=>lines.push(...xs);
p('# Island character canon','',
  '_Generated from `homeworld/src/characters.mjs` by `homeworld/scripts/gen-characters-md.mjs`. Edit the `.mjs`, then run `npm run characters:md` in `homeworld/`. Do not edit this file by hand._','',
  'The friends who live on the Players World island, how they talk, what they do and what they never do. Ages 4–9: short, warm, gentle; faith lines are simple and never preachy.','');

const glance=(title,table)=>{
  p(`## ${title}`,'','| Friend | Role (id) | Leadership | Strengths | Still learning | Tasks | Bible |','|---|---|---|---|---|---|---|');
  for(const c of Object.values(table))p(`| ${c.name} | ${c.roleName}${c.roleId?` (\`${c.roleId}\`)`:''} | ${c.leadership??1} | ${cell(list(c.strengths))} | ${cell(list(c.weaknesses))} | ${cell(tasks(c))} | ${cell(c.bibleRef||'—')} |`);
  p('');
};
glance('At a glance — the island friends',CHARACTERS);
glance('Bible friends (from the reward pool)',BIBLE_CHARACTERS);

p('## Roles','','Each role runs on autopilot chores the island already has (residents.js `pickSkillChores`), so a new role never needs new game code.','',
  '| Role id | Name | Icon | Skill area | Autopilot chores | The foreman usually gives them |','|---|---|---|---|---|---|');
for(const [id,r] of Object.entries(ROLES))p(`| \`${id}\` | ${r.name} | \`${r.icon}\` | ${r.area} | ${r.chores.join(', ')} | ${cell(r.usually)} |`);
p('');

p('## How the foreman is chosen','','`foremanFor(residents)` picks the resident with the highest `leadership` (0–5). Ties go to Adam if he is one of them (the island\'s default foreman), otherwise to whoever arrived first. With nobody ashore it is Adam. So Joseph (5) runs the morning meeting as soon as he lives on the island; Moses, Deborah and Jesus are also 5; Joshua, Esther, Nehemiah, Solomon, Paul, David and Abraham are 4.','');
p('## Friends not in these tables','','A story friend from the reward pool who is in neither table is looked up once through `POST /api/island/character-profile` (Gemini Flash, validated against the same rules, cached in Mongo by normalised name and on the device under `godlykids_island_charprofile_v1:<key>`). Until the answer arrives the generic helper card shows; the About card upgrades silently. Travellers with made-up names never trigger a lookup.','');

const section=(key,c,extra='')=>{
  p(`## ${c.title}${extra}`,'',`${c.bio}`,'');
  p('| | |','|---|---|',
    `| Key | \`${key}\` |`,
    `| Role | ${c.roleName}${c.roleId?` (\`${c.roleId}\`, icon \`${c.icon}\`)`:` (icon \`${c.icon}\`)`} |`,
    `| Personality | ${cell(c.personality.join(', '))} |`,
    `| Voice | ${cell(c.voice)} |`,
    `| Strengths | ${cell(list(c.strengths))} |`,
    `| Still learning | ${cell(list(c.weaknesses))} |`,
    `| Tasks | ${cell(tasks(c))} |`,
    `| Daily rhythm | ${cell(c.dailyRhythm)} |`,
    `| Relationships | ${cell(c.relationships)} |`,
    `| Faith | ${cell(c.faith)} |`,
    `| Never | ${cell(c.limits.join('; '))} |`,
    `| Leadership | ${c.leadership??1} / 5 |`,
    ...(c.bibleRef?[`| Bible | ${cell(c.bibleRef)} — ${cell(c.storyLine)} |`]:[]),
    `| Card line | The foreman picks the day’s jobs — ${c.name} usually gets ${c.usually}. |`,
    `| Foreman note | ${cell(c.foremanNote)} |`,'');
  p('Prompt summary (`promptSummary`):','','```',promptSummary(c),'```','');
};
p('# The island friends','');
for(const [key,c] of Object.entries(CHARACTERS))section(key,c,key==='generic'?' (template for unnamed friends)':'');
p('# Bible friends','');
for(const [key,c] of Object.entries(BIBLE_CHARACTERS))section(key,c);

p('## Where this is used','',
  'Files that read the canon today, and the ones that still restate character facts and should move over.','',
  '| File | Status | What |','|---|---|---|');
for(const u of CONSUMERS)p(`| \`${u.file}\` | ${u.status==='now'?'reads canon now':'later'} | ${cell(u.what)} |`);
p('');

fs.writeFileSync(out,lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(),out)} (${Object.keys(CHARACTERS).length} island friends + ${Object.keys(BIBLE_CHARACTERS).length} Bible friends)`);
